/**
 * Locale + message catalogue shared by the renderer and the main process.
 *
 * It lives under `src/electron` so the main-process build (`src/electron` is the
 * tsconfig root) picks it up without changing the compiled output layout; the
 * renderer imports it the same way it already imports `./type.js`.
 *
 * Nothing here touches Vue, `window` or Electron, so both processes can use it
 * and the tests can import it directly.
 */

export const LOCALES = ['en', 'vi', 'ja'] as const
export type Locale = (typeof LOCALES)[number]

