const CATALOGUES: Record<Locale, Record<MessageKey, string>> = { en, vi, ja }

/**
 * Looks up a message and fills `{placeholder}` slots. A missing key can only
 * happen if a locale is added without a catalogue, so it degrades to the key
 * itself instead of throwing inside a render.
 */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>
): string {
  const template = CATALOGUES[locale]?.[key] ?? en[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  )
}
